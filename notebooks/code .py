def vectorize_data(train_df, valid_df, test_df, text_column='cleaned_text', sentiment_column='sentiment'):
    """
    Vectorizes text data using TF-IDF and prepares it for model training, validation, and testing.

    Input:
    - train_df (pd.DataFrame): The DataFrame containing the training data.
    - valid_df (pd.DataFrame): The DataFrame containing the validation data.
    - test_df (pd.DataFrame): The DataFrame containing the test data.
    - text_column (str): The column name in the DataFrames that contains the cleaned text data. Default is 'cleaned_text'.
    - sentiment_column (str): The column name in the DataFrames that contains the sentiment labels. Default is 'sentiment'.

    Output:
    - X_train_tfidf (scipy.sparse.csr.csr_matrix): The TF-IDF vectorized features of the training set.
    - y_train (pd.Series): The labels for the training set.
    - X_valid_tfidf (scipy.sparse.csr.csr_matrix): The TF-IDF vectorized features of the validation set.
    - y_valid (pd.Series): The labels for the validation set.
    - X_test_tfidf (scipy.sparse.csr.csr_matrix): The TF-IDF vectorized features of the test set.
    - y_test_dis (pd.Series): The 'out_label_model_dis' labels for the test set.
    - y_test_unsup (pd.Series): The 'out_label_model_unsup' labels for the test set.
    - tfidf_vectorizer (TfidfVectorizer): The TF-IDF vectorizer object, fitted on the training data.

    Functionality:
    1. **Text Preprocessing**:
       - Calls `preprocess_text` on the training, validation, and test DataFrames to clean and prepare the text data.

    2. **Feature and Label Separation**:
       - Extracts features (text data) and labels from the DataFrames.
       - The features are extracted from the column specified by `text_column`.
       - The labels for training and validation are from the `sentiment_column`.
       - The test set has two different label columns: 'out_label_model_dis' and 'out_label_model_unsup'.

    3. **TF-IDF Vectorization**:
       - Initializes a `TfidfVectorizer` with English stop words to transform text data into numerical form.
       - Fits the vectorizer on the training data and transforms it into TF-IDF features.
       - Uses the same vectorizer to transform the validation and test data, ensuring consistency in feature representation.

    4. **Return Values**:
       - Returns the TF-IDF transformed features and the corresponding labels for training, validation, and testing, along with the fitted TF-IDF vectorizer.
    """

    # Preprocess text data
    train_df = preprocess_text(train_df, text_column)
    valid_df = preprocess_text(valid_df, text_column)
    test_df = preprocess_text(test_df, text_column)

    # Split data into features and labels
    X_train = train_df[text_column]
    y_train = train_df[sentiment_column]
    X_valid = valid_df[text_column]
    y_valid = valid_df[sentiment_column]
    X_test = test_df[text_column]
    y_test_dis = test_df['out_label_model_dis']
    y_test_unsup = test_df['out_label_model_unsup']

    # Initialize TF-IDF Vectorizer
    tfidf_vectorizer = TfidfVectorizer(stop_words='english')

    # Fit and transform training data
    X_train_tfidf = tfidf_vectorizer.fit_transform(X_train)

    # Transform validation and test data using the same vectorizer
    X_valid_tfidf = tfidf_vectorizer.transform(X_valid)
    X_test_tfidf = tfidf_vectorizer.transform(X_test)

    return X_train_tfidf, y_train, X_valid_tfidf, y_valid, X_test_tfidf, y_test_dis, y_test_unsup, tfidf_vectorizer

