def preprocess_text(df, text_column='text'):
    """
    Preprocesses the text data in a DataFrame by performing the following steps:
    1. Handling missing values
    2. Cleaning text (lowercasing, removing digits, and punctuation)
    3. Tokenizing and removing stop words

    Parameters:
    df (pd.DataFrame): The DataFrame containing the text data.
    text_column (str): The column name containing the text to preprocess.

    Returns:
    pd.DataFrame: The DataFrame with an additional column 'cleaned_text' containing the processed text.
    """
    # Download NLTK resources for stopwords and tokenization in case some thing went wrong and it is need it.
    nltk.download('stopwords')
    nltk.download('punkt')

    # Fill missing values in the specified text column with empty strings
    df[text_column] = df[text_column].fillna('')

    # Define function to clean text: lowercasing, removing digits, and punctuation
    def clean_text(text):
        """
        Cleans the text by:
        - Converting to lowercase
        - Removing digits
        - Removing punctuation

        Parameters:
        text (str): The text to clean.

        Returns:
        str: The cleaned text.
        """
        if isinstance(text, str):
            text = text.lower()  # Convert to lowercase
            text = re.sub(r'\d+', '', text)  # Remove digits
            text = re.sub(r'[^\w\s]', '', text)  # Remove punctuation
        return text

    # Apply text cleaning function to the specified text column
    df['cleaned_text'] = df[text_column].apply(clean_text)

    # Define stop words set from NLTK
    stop_words = set(stopwords.words('english'))

    # Define function to tokenize text and remove stop words
    def tokenize_and_filter(text):
        """
        Tokenizes the text and removes stop words.

        Parameters:
        text (str): The cleaned text to tokenize and filter.

        Returns:
        str: The filtered text with stop words removed.
        """
        tokens = word_tokenize(text)  # Tokenize text
        filtered_tokens = [word for word in tokens if word not in stop_words]  # Remove stop words
        return ' '.join(filtered_tokens)  # Rejoin tokens into a single string

    # Apply tokenization and stop words removal to the cleaned text
    df['cleaned_text'] = df['cleaned_text'].apply(tokenize_and_filter)

    return df
